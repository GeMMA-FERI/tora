function titleCaseToken(token: string): string {
  if (!token) return token;
  const lower = token.toLowerCase();
  if (ACRONYMS.has(lower)) return lower.toUpperCase();
  return `${lower[0].toUpperCase()}${lower.slice(1)}`;
}

function toTitleCase(name: string): string {
  return name
    .split(/[_\s]+/g)
    .filter(Boolean)
    .map(titleCaseToken)
    .join(" ");
}

export function makePortLabel(name: string, direction: PortDirection): string {
  const directionMap = direction === "input" ? INPUT_LABEL_MAP : OUTPUT_LABEL_MAP;
  const label = directionMap[name] ?? LABEL_MAP[name];
  if (label) {
    return label;
  } else {
    console.log(`Warning: No label found for port name "${name}" in direction "${direction}". Using title case as fallback.`);
  }
  return toTitleCase(name);
}
