import { editorTypeForProperty } from "./editor.js";
import { uuidToCppCtor } from "./naming.js";

// Shared by the handwritten processor's generated binding and the registry.
// Keep this UUID and these terminal keys compatible with existing saved graphs.
export function tensorLoaderBinding() {
  const port = (key: string, property: string, description: string) => {
    const cppPropertyType = `Data::${property}<${JSON.stringify(key)}, ${JSON.stringify(description)}>`;
    return { key, description, cppPropertyType, editorType: editorTypeForProperty(cppPropertyType) };
  };
  return {
    implementationId: "3a6a2744-f014-45d9-bb93-3d96c9f6b152",
    name: "Load Tensor",
    description: "Loads a named tensor from a Safetensors file into owned CPU memory.",
    inputs: {
      file: port("File", "FilePathProperty", "Safetensors file. Relative paths require Base Directory."),
      name: port("Tensor Name", "StringProperty", "Exact tensor key in the file, for example linear.weight."),
      base: port("Base Directory", "StringProperty", "Optional absolute directory used to resolve a relative File."),
    },
    outputs: { tensor: port("Tensor", "TensorProperty", "Loaded contiguous CPU tensor with its original shape and dtype.") },
  };
}

export type TensorLoaderBinding = ReturnType<typeof tensorLoaderBinding>;

export function renderTensorLoaderBinding(): string {
  const binding = tensorLoaderBinding();
  const aliases = [
    ...Object.entries(binding.inputs).map(([name, port]) => `    using In_${name} = ${port.cppPropertyType};`),
    ...Object.entries(binding.outputs).map(([name, port]) => `    using Out_${name} = ${port.cppPropertyType};`),
  ];
  return `// Auto-generated by tora transpiler. Do not edit manually.
#pragma once
#include <Helpers.hpp>

struct TensorLoaderBinding {
    static constexpr auto name() { return std::string_view(${JSON.stringify(binding.name)}); }
    static constexpr auto description() { return std::string_view(${JSON.stringify(binding.description)}); }
    static constexpr auto implementation_id() { return ${uuidToCppCtor(binding.implementationId)}; }
${aliases.join("\n")}
};
`;
}
